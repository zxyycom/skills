import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { removeStaleGeneratedTypeScriptDeclarations } from "./generated-declaration-cleanup.ts";

test("generated declaration cleanup only removes verified stale declaration files", async () => {
  const generatedDeclarationsTempRoot = await fs.mkdtemp(
    path.join(os.tmpdir(), "generated-declaration-cleanup-test-")
  );
  try {
    const declarationOutputDirectory = path.join(
      generatedDeclarationsTempRoot,
      "declarations"
    );
    const artifactName = "example TypeScript declaration";
    const generatedDeclaration = [
      "/*",
      ` * Generated ${artifactName}. Do not edit this file directly.`,
      " */",
      "export {};",
      ""
    ].join("\n");
    const expectedDeclarationPath = path.join(
      declarationOutputDirectory,
      "current.d.mts"
    );
    const staleDeclarationPath = path.join(
      declarationOutputDirectory,
      "stale.d.mts"
    );
    const unmanagedDeclarationPath = path.join(
      declarationOutputDirectory,
      "manual.d.mts"
    );
    const unexpectedDirectoryPath = path.join(
      declarationOutputDirectory,
      "unexpected"
    );
    const linkedDeclarationPath = path.join(
      declarationOutputDirectory,
      "linked.d.mts"
    );
    const nestedCurrent = path.join(
      declarationOutputDirectory,
      "nested",
      "current.d.mts"
    );
    const nestedStale = path.join(
      declarationOutputDirectory,
      "nested",
      "stale.d.mts"
    );
    const retiredDirectory = path.join(declarationOutputDirectory, "retired");
    await fs.mkdir(unexpectedDirectoryPath, { recursive: true });
    await fs.mkdir(path.dirname(nestedCurrent), { recursive: true });
    await fs.mkdir(retiredDirectory);
    await Promise.all([
      fs.writeFile(nestedCurrent, generatedDeclaration),
      fs.writeFile(nestedStale, generatedDeclaration),
      fs.writeFile(
        path.join(retiredDirectory, "stale.d.mts"),
        generatedDeclaration
      ),
      fs.writeFile(expectedDeclarationPath, generatedDeclaration, "utf8"),
      fs.writeFile(staleDeclarationPath, generatedDeclaration, "utf8"),
      fs.writeFile(
        unmanagedDeclarationPath,
        "export type Manual = true;\n",
        "utf8"
      ),
      fs.symlink(unmanagedDeclarationPath, linkedDeclarationPath)
    ]);
    const options = {
      declarationArtifactName: artifactName,
      declarationOutputDirectory,
      expectedPaths: new Set([expectedDeclarationPath, nestedCurrent]),
      sourcePath: "tools/example/src/cli.ts",
      workspaceRoot: generatedDeclarationsTempRoot
    };

    assert.deepEqual(
      await removeStaleGeneratedTypeScriptDeclarations({
        ...options,
        mode: "check"
      }),
      { changed: true, hasUnsupportedEntries: true }
    );
    assert.equal((await fs.lstat(staleDeclarationPath)).isFile(), true);
    assert.equal((await fs.lstat(nestedStale)).isFile(), true);

    assert.deepEqual(
      await removeStaleGeneratedTypeScriptDeclarations({
        ...options,
        mode: "write"
      }),
      { changed: true, hasUnsupportedEntries: true }
    );
    await assert.rejects(fs.lstat(staleDeclarationPath), { code: "ENOENT" });
    await assert.rejects(fs.lstat(nestedStale), { code: "ENOENT" });
    await assert.rejects(fs.lstat(retiredDirectory), { code: "ENOENT" });
    assert.equal((await fs.lstat(nestedCurrent)).isFile(), true);
    assert.equal((await fs.lstat(expectedDeclarationPath)).isFile(), true);
    assert.equal((await fs.lstat(unmanagedDeclarationPath)).isFile(), true);
    assert.equal((await fs.lstat(unexpectedDirectoryPath)).isDirectory(), true);
    assert.equal(
      (await fs.lstat(linkedDeclarationPath)).isSymbolicLink(),
      true
    );
  } finally {
    await fs.rm(generatedDeclarationsTempRoot, {
      force: true,
      recursive: true
    });
  }
});

test("generated declaration cleanup preserves nested unmanaged members and directory links", async () => {
  const directory = await fs.mkdtemp(
    path.join(os.tmpdir(), "declaration-ownership-")
  );
  const output = path.join(directory, "declarations");
  const mixed = path.join(output, "mixed");
  const outside = path.join(directory, "outside");
  const linked = path.join(output, "linked-directory");
  const empty = path.join(output, "unmanaged-empty");
  const generated =
    "/*\n * Generated fixture declaration. Do not edit this file directly.\n */\nexport {};\n";
  const manual = "export type Manual = true;\n";
  try {
    await fs.mkdir(mixed, { recursive: true });
    await fs.mkdir(outside);
    await fs.mkdir(empty);
    await fs.writeFile(path.join(mixed, "stale.d.mts"), generated);
    await fs.writeFile(path.join(mixed, "manual.d.mts"), manual);
    await fs.writeFile(path.join(outside, "protected.d.mts"), generated);
    await fs.symlink(
      outside,
      linked,
      process.platform === "win32" ? "junction" : "dir"
    );
    const options = {
      declarationArtifactName: "fixture declaration",
      declarationOutputDirectory: output,
      expectedPaths: new Set<string>(),
      sourcePath: "src/cli.ts",
      workspaceRoot: directory
    };
    assert.deepEqual(
      await removeStaleGeneratedTypeScriptDeclarations({
        ...options,
        mode: "check"
      }),
      {
        changed: true,
        hasUnsupportedEntries: true
      }
    );
    assert.equal(
      await fs.readFile(path.join(mixed, "stale.d.mts"), "utf8"),
      generated
    );
    assert.deepEqual(
      await removeStaleGeneratedTypeScriptDeclarations({
        ...options,
        mode: "write"
      }),
      {
        changed: true,
        hasUnsupportedEntries: true
      }
    );
    await assert.rejects(fs.lstat(path.join(mixed, "stale.d.mts")), {
      code: "ENOENT"
    });
    assert.equal(
      await fs.readFile(path.join(mixed, "manual.d.mts"), "utf8"),
      manual
    );
    assert.equal(
      await fs.readFile(path.join(outside, "protected.d.mts"), "utf8"),
      generated
    );
    assert.equal((await fs.lstat(linked)).isSymbolicLink(), true);
    assert.equal((await fs.lstat(empty)).isDirectory(), true);
    assert.equal((await fs.lstat(mixed)).isDirectory(), true);
  } finally {
    await fs.rm(directory, { recursive: true, force: true });
  }
});
